  await page.getByRole('button', { name: 'Keep editing' }).click()
  await expect(dialog.getByLabel('Narration', { exact: true })).toHaveValue('Unsaved text')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
